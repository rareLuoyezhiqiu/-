test('真实 IndexedDB 写入失败保留输入并可重试；删除失败保留记录', async ({page}) => {
  await add(page,'保留的记录');
  await page.getByRole('button',{name:'＋ 记一下',exact:true}).click();
  await page.getByLabel('想法内容').fill('这条不能丢');
  await page.evaluate(() => { window.originalPut=IDBObjectStore.prototype.put; IDBObjectStore.prototype.put=function(){throw new DOMException('Full','QuotaExceededError')}; });
  await expect(page.getByRole('alert')).toContainText('草稿未保存');
  await page.getByRole('button',{name:'保存想法'}).click();
  await expect(page.locator('#editor').getByText('保存失败，输入已保留。请检查存储空间或权限后重试。')).toBeVisible();
  await expect(page.getByLabel('想法内容')).toHaveValue('这条不能丢');
  await page.evaluate(() => IDBObjectStore.prototype.put=window.originalPut);
  await page.getByRole('button',{name:'保存想法'}).click();
  await expect(page.locator('.note')).toHaveCount(2);
  await page.evaluate(() => { window.originalDelete=IDBObjectStore.prototype.delete; IDBObjectStore.prototype.delete=function(){throw new DOMException('Denied','UnknownError')}; });
  await page.locator('.note').first().getByText('删除',{exact:true}).click();
  await page.getByRole('button',{name:'确认删除'}).click();
  await expect(page.getByRole('alert')).toContainText('删除失败');
  await expect(page.locator('.note')).toHaveCount(2);
  await page.evaluate(() => IDBObjectStore.prototype.delete=window.originalDelete);
  await page.getByRole('button',{name:'确认删除'}).click();
  await expect(page.locator('.note')).toHaveCount(1);
});
test('数据库打不开时明确报错并支持重新读取', async ({page}) => {
  await page.addInitScript(() => { const open=IDBFactory.prototype.open; IDBFactory.prototype.open=function(){throw new DOMException('Denied','SecurityError')}; window.restore=()=>IDBFactory.prototype.open=open; });
  await page.reload();
  await expect(page.getByRole('alert')).toContainText('无法读取本机数据');
  await expect(page.getByText('第一条想法，留给此刻。')).not.toBeVisible();
  await page.evaluate(()=>window.restore());
  await page.getByRole('button',{name:'重新读取'}).click();
  await expect(page.getByText('第一条想法，留给此刻。')).toBeVisible();
});
