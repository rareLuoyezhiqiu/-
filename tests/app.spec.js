test('首次缓存后离线重开并保存，JSON 导出不含草稿', async ({page,context}) => {
  await add(page,'离线之前');
  await page.evaluate(async()=>{await navigator.serviceWorker.ready;});
  await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true);
  await context.setOffline(true);await page.reload();
  await expect(page.locator('.note p')).toHaveText('离线之前');
  await add(page,'离线记录'); await page.reload();
  await expect(page.locator('.note')).toHaveCount(2);
  await page.getByRole('button',{name:'＋ 记一下',exact:true}).click();await page.getByLabel('想法内容').fill('不要导出草稿');await page.getByRole('button',{name:'收起'}).click();
  await page.getByText('数据备份与桌面安装').click();
  const download=page.waitForEvent('download');await page.getByText('导出 JSON 备份').click();
  const data=JSON.parse(await readFile(await (await download).path(),'utf8'));
  expect(data.formatVersion).toBe(2);expect(data.notes.map(n=>n.content)).toEqual(['离线记录','离线之前']);expect(data.drafts).toBeUndefined();
});
